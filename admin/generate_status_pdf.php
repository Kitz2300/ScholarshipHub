<?php
include __DIR__ . '/../includes/conn.php';
include __DIR__ . '/../includes/check_permission.php';
session_start();

// Ensure user is logged in
if (!isset($_SESSION['user_id']) || ($_SESSION['role'] !== 'admin' && $_SESSION['role'] !== 'staff')) {
    die("Unauthorized access.");
}

// Get filter parameters
$school_year = isset($_GET['school_year']) ? trim($_GET['school_year']) : 'all';
$semester    = isset($_GET['semester']) ? trim($_GET['semester']) : 'all';

// Strip spaces for flexible SQL comparisons ("2028 - 2029" vs "2028-2029")
$clean_school_year = str_replace(' ', '', $school_year);

// Build JOIN conditions to match Dashboard status query logic
$join_sql = "si.academic_status = statuses.academic_status AND si.is_archived = 0";

$bind_types = "";
$bind_params = [];

if ($school_year !== 'all' && !empty($school_year)) {
    $join_sql .= " AND REPLACE(si.school_year, ' ', '') = ?";
    $bind_types .= "s";
    $bind_params[] = $clean_school_year;
}

if ($semester !== 'all' && !empty($semester)) {
    $join_sql .= " AND si.semester = ?";
    $bind_types .= "s";
    $bind_params[] = $semester;
}

$sql = "SELECT 
            statuses.academic_status, 
            COALESCE(COUNT(si.id), 0) AS status_count
        FROM (
            SELECT 'Enrolled' AS academic_status
            UNION SELECT 'Not Enrolled'
            UNION SELECT 'Graduated'
            UNION SELECT 'Dropped'
            UNION SELECT 'Transferred'
            UNION SELECT 'Leave of Absence'
        ) AS statuses
        LEFT JOIN scholar_info si ON $join_sql
        GROUP BY statuses.academic_status
        ORDER BY FIELD(statuses.academic_status, 'Enrolled', 'Not Enrolled', 'Graduated', 'Dropped', 'Transferred', 'Leave of Absence')";

$stmt = $conn->prepare($sql);
if (!empty($bind_params)) {
    $stmt->bind_param($bind_types, ...$bind_params);
}
$stmt->execute();
$result = $stmt->get_result();

$report_data = [];
$total_scholars = 0;

while ($row = $result->fetch_assoc()) {
    $report_data[] = $row;
    $total_scholars += (int)$row['status_count'];
}
$stmt->close();

// Fetch Generator Info & Role
$user_id = $_SESSION['user_id'];
$u_sql = "SELECT CONCAT_WS(' ', given_name, last_name) as name, role FROM scholarship_users WHERE id = ?";
$u_stmt = $conn->prepare($u_sql);
$u_stmt->bind_param("i", $user_id);
$u_stmt->execute();
$u_res = $u_stmt->get_result()->fetch_assoc();
$user_name = !empty($u_res['name']) ? $u_res['name'] : 'System Administrator';
$user_role = strtolower($u_res['role'] ?? 'admin');
$u_stmt->close();

// Fetch Coordinator Name (Admin) if report is generated by Staff
$coordinator_name = '';
if ($user_role === 'staff') {
    $coord_sql = "SELECT CONCAT_WS(' ', given_name, last_name) as name FROM scholarship_users WHERE role = 'admin' AND is_archived = 0 ORDER BY id ASC LIMIT 1";
    $coord_res = $conn->query($coord_sql);
    if ($coord_res && $coord_row = $coord_res->fetch_assoc()) {
        $coordinator_name = $coord_row['name'];
    }
}

$filter_sy_text = ($school_year === 'all') ? 'All School Years' : 'S.Y. ' . $school_year;
$filter_sem_text = ($semester === 'all') ? 'All Semesters' : $semester;
$date_generated = date('F d, Y h:i A');

$css_file_path = __DIR__ . '/../assets/css/generate_summary_pdf.css';
$css_version = file_exists($css_file_path) ? filemtime($css_file_path) : time();

ob_start();
?>
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>Scholar Status Summary Report - PIT ScholarshipHub</title>
    <link rel="stylesheet" href="../assets/css/generate_summary_pdf.css?v=<?= $css_version ?>">
    <link rel="icon" href="../assets/images/PIT%20LOGO.png">
</head>
<body>

    <div class="action-bar no-print">
        <button type="button" onclick="closeReportTab()" class="btn btn-secondary">← Back to Dashboard</button>
        <button type="button" onclick="window.print()" class="btn btn-primary">🖨️ Print / Save as PDF</button>
    </div>

    <div class="report-card">
        <!-- Official Header -->
        <div class="report-header">
            <img src="../assets/images/PIT%20LOGO.png" alt="PIT Logo" class="logo-img">
            <h1>Palompon Institute of Technology</h1>
            <h2>Scholarship Office — Academic Status Summary Report</h2>
            <p>Palompon, Leyte, Philippines</p>
        </div>

        <!-- Filter Context -->
        <div class="meta-banner">
            <div class="meta-item"><strong>School Year:</strong> <?= htmlspecialchars($filter_sy_text) ?></div>
            <div class="meta-item"><strong>Semester:</strong> <?= htmlspecialchars($filter_sem_text) ?></div>
            <div class="meta-item"><strong>Date:</strong> <?= $date_generated ?></div>
        </div>

        <!-- 2-COLUMN TABLE -->
        <table>
            <thead>
                <tr>
                    <th>Academic Status</th>
                    <th class="text-right">Scholar Count</th>
                </tr>
            </thead>
            <tbody>
                <?php if (!empty($report_data)): ?>
                    <?php foreach ($report_data as $row): ?>
                        <tr>
                            <td>
                                <strong><?= htmlspecialchars($row['academic_status']) ?></strong>
                            </td>
                            <td class="text-right"><strong><?= number_format($row['status_count']) ?></strong></td>
                        </tr>
                    <?php endforeach; ?>
                <?php else: ?>
                    <tr>
                        <td colspan="2" style="text-align: center; color: #64748b; padding: 20px;">No scholar records found for the selected period.</td>
                    </tr>
                <?php endif; ?>
            </tbody>
            <tfoot>
                <tr>
                    <td>TOTAL SCHOLARS</td>
                    <td class="text-right"><?= number_format($total_scholars) ?></td>
                </tr>
            </tfoot>
        </table>

        <!-- Signature Section Dynamic Logic -->
        <?php if ($user_role === 'staff'): ?>
            <!-- STAFF GENERATED: Left = Prepared By (Staff), Right = Noted By (Coordinator) -->
            <div class="signature-section staff-sig">
                <div class="sig-block">
                    <div class="sig-label">Prepared By:</div>
                    <div class="sig-line"><strong><?= htmlspecialchars($user_name) ?></strong></div>
                    <div class="sig-title">Scholarship Staff</div>
                </div>
                <div class="sig-block">
                    <div class="sig-label">Noted By:</div>
                    <div class="sig-line"><strong><?= htmlspecialchars($coordinator_name) ?></strong></div>
                    <div class="sig-title">Scholarship Coordinator</div>
                </div>
            </div>
        <?php else: ?>
            <!-- ADMIN GENERATED: Single block aligned LEFT with NO "Noted By:" text -->
            <div class="signature-section admin-sig">
                <div class="sig-block">
                    <div class="sig-line" style="margin-top: 35px;"><strong><?= htmlspecialchars($user_name) ?></strong></div>
                    <div class="sig-title">Scholarship Coordinator</div>
                </div>
            </div>
        <?php endif; ?>
    </div>

    <script>
    function closeReportTab() {
        window.close();
        setTimeout(function() {
            window.location.href = 'dashboard.php';
        }, 300);
    }
    </script>
</body>
</html>
<?php
$html = ob_get_clean();

// Check if Dompdf streamer is requested
if (isset($_GET['download_pdf']) && class_exists('Dompdf\Dompdf')) {
    if (file_exists($css_file_path)) {
        $css_content = file_get_contents($css_file_path);
        $html = str_replace(
            '<link rel="stylesheet" href="../assets/css/generate_summary_pdf.css?v=' . $css_version . '">',
            '<style>' . $css_content . '</style>',
            $html
        );
    }
    
    $dompdf = new \Dompdf\Dompdf();
    $dompdf->loadHtml($html);
    $dompdf->setPaper('letter', 'landscape');
    $dompdf->render();
    $filename = "Scholar_Status_Report_" . str_replace(' ', '_', $school_year) . ".pdf";
    $dompdf->stream($filename, ["Attachment" => false]);
    exit();
}

echo $html;
?>